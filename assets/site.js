function setLang(l) {
  const lang = l === "en" ? "en" : "vi";
  const d = dict[lang];
  document.documentElement.lang = lang;

  const pageType = document.body.dataset.page;
  if (pageType === "home") document.title = d.pageTitleHome;
  else if (pageType === "privacy") document.title = d.pageTitlePrivacy;
  else if (pageType === "terms") document.title = d.pageTitleTerms;

  document.querySelectorAll("[data-v]").forEach(e => {
    if (d[e.dataset.v] !== undefined) e.textContent = d[e.dataset.v];
  });
  document.querySelectorAll("[data-v-html]").forEach(e => {
    if (d[e.dataset.vHtml] !== undefined) e.innerHTML = d[e.dataset.vHtml];
  });
  document.querySelectorAll(".vi").forEach(e => { e.hidden = lang !== "vi"; });
  document.querySelectorAll(".en").forEach(e => { e.hidden = lang !== "en"; });

  const b = document.getElementById("lang");
  if (b) b.textContent = lang === "vi" ? "EN" : "VI";

  try { localStorage.setItem("ViWallet-lang", lang); } catch (e) {}
}

document.addEventListener("DOMContentLoaded", () => {
  let l = "vi";
  try { l = localStorage.getItem("ViWallet-lang") || "vi"; } catch (e) {}
  setLang(l);

  const b = document.getElementById("lang");
  if (b) {
    b.addEventListener("click", () => {
      setLang(document.documentElement.lang === "vi" ? "en" : "vi");
    });
  }

  const y = document.getElementById("year");
  if (y) y.textContent = new Date().getFullYear();
});
